    public FrmEmpleados() {
        initComponents();
        employeeManager = new EmployeeManager();
        for (Employee e : employeeManager.getEmployees()) {
            employeeListModel.addElement(e.getId() + " - " + e.getName());
        }
        lstEmpleados.setModel(employeeListModel);
        lstEmpleados.addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                String selected = lstEmpleados.getSelectedValue();
                if (selected != null) {
                    String id = selected.split(" - ")[0];
                    Employee emp = employeeManager.searchEmployee(id);
                    if (emp != null) {
                        txtCedula.setText(emp.getId());
                        txtNombre.setText(emp.getName());
                        txtFecha.setText(emp.getBirthDate().toString());
                        txtTelefono.setText(emp.getPhone());
                        txtCorreo.setText(emp.getEmail());
                        txtPuesto.setText(emp.getPosition());
                        txtSalario.setText(String.valueOf(emp.getSalary()));

                        txtCedula.setEditable(false);
                        txtNombre.setEditable(false);
                        txtFecha.setEditable(false);
                    }
                } else {
                    limpiar();
                }
            }
        });

        this.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                lstEmpleados.clearSelection();
            }
        });
    }

