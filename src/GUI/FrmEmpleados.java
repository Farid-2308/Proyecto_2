    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            String id = txtCedula.getText();
            String name = txtNombre.getText();
            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate birth = LocalDate.parse(txtFecha.getText(), formatter);
            String phone = txtTelefono.getText();
            String email = txtCorreo.getText();
            String position = txtPuesto.getText();
            double salary = Double.parseDouble(txtSalario.getText());

            Employee emp = new Employee(id, name, birth, phone, email, position, salary);
            employeeManager.addEmployee(emp);

            JOptionPane.showMessageDialog(this, "Empleado agregado correctamente");
            refrescarLista();
            limpiar();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String id = txtCedula.getText();
        employeeManager.removeEmployee(id);

        JOptionPane.showMessageDialog(this, "Empleado eliminado correctamente");
        refrescarLista();
        limpiar();
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            String id = txtCedula.getText();
            String phone = txtTelefono.getText();
            String email = txtCorreo.getText();
            String position = txtPuesto.getText();
            double salary = Double.parseDouble(txtSalario.getText());

            employeeManager.updateEmployee(id, phone, email, position);

            Employee emp = employeeManager.searchEmployee(id);
            if (emp != null) {
                emp.setSalary(salary);
            }

            JOptionPane.showMessageDialog(this, "Empleado actualizado correctamente");
            refrescarLista();
        } catch (HeadlessException | NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String id = txtCedula.getText();
        Employee emp = employeeManager.searchEmployee(id);

        if (emp != null) {
            txtNombre.setText(emp.getName());
            txtFecha.setText(emp.getBirthDate().toString());
            txtTelefono.setText(emp.getPhone());
            txtCorreo.setText(emp.getEmail());
            txtPuesto.setText(emp.getPosition());
            txtSalario.setText(String.valueOf(emp.getSalary()));
            txtCedula.setEditable(false);
            txtNombre.setEditable(false);
            txtFecha.setEditable(false);

            JOptionPane.showMessageDialog(this, "Empleado encontrado");
        } else {
            JOptionPane.showMessageDialog(this, "Empleado no existe");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void refrescarLista() {
        for (Employee e : employeeManager.getEmployees()) {
            employeeListModel.addElement(e.getId() + " - " + e.getName() + " (" + e.getPosition() + ")");
        }
    }
    
    private void limpiar() {
        txtCedula.setText("");
        txtNombre.setText("");
        txtFecha.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        txtPuesto.setText("");
        txtSalario.setText("");
        txtCedula.setEditable(true);
        txtNombre.setEditable(true);
        txtFecha.setEditable(true);
    }
