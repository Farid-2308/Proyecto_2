    private void btnActualizarVehiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarVehiculoActionPerformed
        try {
            String plate = txtPlaca.getText();
            Vehicule v = manager.SearchVehicule(plate);

            if (v != null) {
                v.setBrand(txtMarca.getText());
                v.setModel(txtModelo.getText());
                v.setYear(Integer.parseInt(txtAnio.getText()));
                v.setType(Types.valueOf(cmbTipo.getSelectedItem().toString()));
                v.setStatus(Status.valueOf(cmbEstado.getSelectedItem().toString()));

                JOptionPane.showMessageDialog(this, "Vehículo actualizado correctamente");
            } else {
                JOptionPane.showMessageDialog(this, "Vehículo no encontrado", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnActualizarVehiculoActionPerformed

