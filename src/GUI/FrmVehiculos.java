    private void btnEliminarVehiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarVehiculoActionPerformed
        try {
            String plate = txtPlaca.getText();
            manager.DeleteVehicule(plate);
            JOptionPane.showMessageDialog(this, "Vehículo eliminado con éxito");
        } catch (VehiculoEnUsoException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(),
                    "Vehículo en uso", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnEliminarVehiculoActionPerformed

    private void btnAgregarVehiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarVehiculoActionPerformed
        try {
            String plate = txtPlaca.getText();
            String brand = txtMarca.getText();
            String model = txtModelo.getText();
            int year = Integer.parseInt(txtAnio.getText());

            Types type = Types.valueOf(cmbTipo.getSelectedItem().toString());
            Status status = Status.valueOf(cmbEstado.getSelectedItem().toString());

            Vehicule v = new Vehicule(plate, brand, model, year, type, status);
            manager.AddVehicule(v);

            JOptionPane.showMessageDialog(this, "Vehículo agregado con éxito");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarVehiculoActionPerformed

